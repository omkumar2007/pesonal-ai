    fun getResponse(input: String): String? {
        val cleanInput = input.lowercase(Locale.getDefault()).trim()
            .replace("?", "")
            .replace("!", "")
            .replace(".", "")
        
        if (cleanInput.isEmpty()) return null

        // 1. Search for direct match
        knowledgeBase[cleanInput]?.let { return it.random() }

        // 2. Search for standalone word match (for short words like 'hi')
        val words = cleanInput.split("\\s+".toRegex())
        for (word in words) {
            knowledgeBase[word]?.let { return it.random() }
        }

        // 3. Search for partial match (contains) for longer phrases
        for ((key, responses) in knowledgeBase) {
            if (key.length > 3 && cleanInput.contains(key)) {
                return responses.random()
            }
        }

        return null
    }
